export const PIECE_MAP = Object.fromEntries(PIECES.map((p) => [p.slug, p]));

export function getPiece(slug: string): Piece | undefined {
  return PIECE_MAP[slug];
}

export function similarPieces(piece: Piece, n = 4): Piece[] {
  return PIECES.filter((p) => p.slug !== piece.slug)
    .map((p) => ({
      p,
      score:
        (p.category === piece.category ? 2 : 0) +
        p.styles.filter((s) => piece.styles.includes(s)).length,
    }))
    .sort((a, b) => b.score - a.score)
    .slice(0, n)
    .map((x) => x.p);
}

